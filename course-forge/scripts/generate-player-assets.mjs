#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Turns the player's stylesheet and runtime into a JavaScript module.
 *
 * The player is authored as real .css and .js files so it stays editable and
 * lintable, but the exporter cannot read them from disk at runtime: bundlers
 * do not follow a readFileSync, so a bundled serverless function ships
 * without them and fails on its first request. Making the assets part of the
 * module graph means every bundler carries them.
 */
const here = dirname(fileURLToPath(import.meta.url))
const playerDir = join(here, '..', 'server', 'export', 'player')

export function renderAssets() {
  const css = readFileSync(join(playerDir, 'player.css'), 'utf8')
  const js = readFileSync(join(playerDir, 'player.js'), 'utf8')

  return `// Generated by scripts/generate-player-assets.mjs — do not edit.
// Source: server/export/player/player.css and player.js
export const PLAYER_CSS = ${JSON.stringify(css)}

export const PLAYER_JS = ${JSON.stringify(js)}
`
}

export const assetsPath = join(playerDir, 'assets.js')

const isEntryPoint = process.argv[1] && process.argv[1].endsWith('generate-player-assets.mjs')
if (isEntryPoint) {
  writeFileSync(assetsPath, renderAssets(), 'utf8')
  console.log(`Wrote ${assetsPath}`)
}
